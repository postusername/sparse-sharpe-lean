"""E35: aggregation of results/E35/ into the table of Section 7.4 (tables/e35_table.tex) and tables/e35_table.md.

Per configuration (M, K, k) and per (M, K) over k in {3, 5, 10}: the number of instances, the certificate
(F_h >= (1 - 2 eps) G*_k, eps = 0.05), the optimality test, greedy selection with exchanges optimal (to 1e-9),
the largest gap 1 - F_h/G*_k, the largest loss of greedy selection with exchanges in Sharpe ratio
1 - sqrt(F_h/OPT), branch and bound (all finished?, median and largest time, largest number of nodes), and the
localized scheme (number of instances with no node; among the others the median and largest number of nodes of
the localized box over all guesses, an upper bound on the localized nodes). The MIQP baseline (e35_miqp.py,
results/E35/miqp_*.jsonl) per M and formulation: solved to optimality within the time limit, median time,
largest final gap (dual bound - exact value of the incumbent's support)/exact value, and whether the
incumbent's support is optimal (exact value >= (1 - 1e-6) * branch and bound); the times of branch and bound on the
same instances are read from results/E35/<M>_<K>_<k>.jsonl (not from the copies in the MIQP records, which hold the
times of the run of E35 that the MIQP run read).
Usage: python3 -I e35_table.py [results_dir] > tables/e35_table.md   (also writes tables/e35_table.tex)
"""
import glob
import json
import math
import os
import statistics as st
import sys

here = os.path.dirname(os.path.abspath(__file__))
rdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'results', 'E35')
EPS = 0.05


def load(M, K, k):
    p = os.path.join(rdir, f'{M}_{K}_{k}.jsonl')
    if not os.path.exists(p):
        return []
    return [json.loads(l) for l in open(p) if l.strip()]


def agg(R):
    R = [r for r in R if not r.get('skip')]
    n = len(R)
    if n == 0:
        return None
    cert = sum(r['cert'] for r in R)
    test = sum(r['test'] for r in R)
    gopt = sum(r['greedy_opt'] for r in R)
    gap = max(r['gap'] for r in R)
    loss = max(1 - math.sqrt(min(1.0, r['Fh'] / r['bnb'])) for r in R)
    done = all(r['bnb_done'] for r in R)
    times = [r['bnb_time'] for r in R]
    nodes = max(r['bnb_nodes'] for r in R)
    loc0 = sum(1 for r in R if r['loc_cube'] == 0)
    locs = [r['loc_cube'] for r in R if r['loc_cube'] > 0]
    return dict(n=n, cert=cert, test=test, gopt=gopt, gap=gap, loss=loss, done=done, tmed=st.median(times),
                tmax=max(times), nodes=nodes, loc0=loc0, locmed=st.median(locs) if locs else None,
                locmax=max(locs) if locs else None)


def fmt_int(x):
    if x is None:
        return '---'
    if x < 1e4:
        return '%d' % x
    e = int(math.floor(math.log10(x)))
    return '%.1f\\cdot10^{%d}' % (x / 10 ** e, e)


Ms, Ks, ks = (50, 200, 1000, 2000), (1, 2, 3), (3, 5, 10)
out = ['# E35: the stress regime at scale (generated by e35_table.py)', '',
       'eps = 0.05; reference: branch and bound of Section 6.3 (relative tolerance 1e-9, time limit 600 s).', '',
       '| M | K | k | n | cert | test | greedy opt | max gap | max SR loss | B&B done | B&B t med / max, s | '
       'B&B nodes max | loc: 0 nodes | loc nodes med / max |', '|' + '---|' * 14]
rows_tex = []
for M in Ms:
    for K in Ks:
        allR = []
        for k in ks:
            R = load(M, K, k)
            allR += R
            a = agg(R)
            if a is None:
                continue
            out.append('| %d | %d | %d | %d | %d | %d | %d | %.3g | %.3g | %s | %.2f / %.2f | %d | %d | %s / %s |' % (
                M, K, k, a['n'], a['cert'], a['test'], a['gopt'], a['gap'], a['loss'], a['done'], a['tmed'],
                a['tmax'], a['nodes'], a['loc0'], a['locmed'], a['locmax']))
        a = agg(allR)
        if a is None:
            continue
        out.append('| **%d** | **%d** | all | %d | %d | %d | %d | %.3g | %.3g | %s | %.2f / %.2f | %d | %d | %s / %s |' % (
            M, K, a['n'], a['cert'], a['test'], a['gopt'], a['gap'], a['loss'], a['done'], a['tmed'], a['tmax'],
            a['nodes'], a['loc0'], a['locmed'], a['locmax']))
        rows_tex.append('%d & %d & %d & %d & %d & %.1f & %.1f & %.2f & %.1f & %d & %d & $%s$\\\\' % (
            M, K, a['n'], a['cert'], a['gopt'], 100 * a['gap'], 100 * a['loss'], a['tmed'], a['tmax'], a['nodes'],
            a['loc0'], fmt_int(a['locmed'])))
    rows_tex.append('\\midrule' if M != Ms[-1] else '')

# MIQP
REF = {}


def ref_time(r):
    key = (r['M'], r['K'], r['k'])
    if key not in REF:
        REF[key] = {x['it']: x for x in load(*key) if 'it' in x}
    x = REF[key][r['it']]
    assert abs(x['bnb'] - r['bnb']) <= 1e-9 * abs(r['bnb']), (key, r['it'])
    return x['bnb_time']


out += ['', '## MIQP baseline (e35_miqp.py)', '',
        '| M | formulation | instances | optimal in time | median time, s | max time, s | max final gap | '
        'support optimal | B&B median / max time, s (same instances) |', '|' + '---|' * 9]
miqp = {}
for p in sorted(glob.glob(os.path.join(rdir, 'miqp_*.jsonl'))):
    for l in open(p):
        if not l.strip():
            continue
        r = json.loads(l)
        for f in ('persp_gurobi', 'persp_scip', 'bigM_scip'):
            if f in r:
                miqp.setdefault((r['M'], f), []).append((r, r[f]))
mtex = []
for M in Ms:
    for f in ('persp_gurobi', 'persp_scip', 'bigM_scip'):
        L = miqp.get((M, f))
        if not L:
            continue
        ok = [o for _, o in L if 'error' not in o]
        opt = sum(1 for o in ok if o['status'] == 'optimal')
        times = [o['time'] for o in ok]
        gaps = [o['gap'] for o in ok if o.get('gap') is not None]
        nosol = sum(1 for o in ok if o.get('exact') is None)
        supopt = sum(1 for r, o in L if o.get('exact') is not None and o['exact'] >= (1 - 1e-6) * r['bnb'])
        bt = [ref_time(r) for r, _ in L]
        out.append('| %d | %s | %d | %d | %.1f | %.1f | %s | %d | %.2f / %.2f |' % (
            M, f, len(L), opt, st.median(times) if times else float('nan'), max(times) if times else float('nan'),
            '%.3g' % max(gaps) if gaps else '-', supopt, st.median(bt), max(bt)))
        if nosol:
            out[-1] += ' (no incumbent: %d)' % nosol
        name = {'persp_gurobi': 'Gurobi, perspective', 'persp_scip': 'SCIP, perspective', 'bigM_scip': 'SCIP, big-$M$'}[f]
        mtex.append((M, name, len(L), opt, st.median(times) if times else float('nan'),
                     max(gaps) if gaps else None, supopt, st.median(bt), max(bt)))
print('\n'.join(out))
os.makedirs(os.path.join(here, 'tables'), exist_ok=True)
with open(os.path.join(here, 'tables', 'e35_table.tex'), 'w') as fh:
    fh.write('% generated by e35_table.py\n' + '\n'.join(r for r in rows_tex if r) + '\n')
with open(os.path.join(here, 'tables', 'e35_miqp.tex'), 'w') as fh:
    fh.write('% generated by e35_table.py: the MIQP baseline (not a table of the paper; the numbers are quoted in the text)\n')
    for t in mtex:
        fh.write('%d & %s & %d & %d & %.1f & %s & %d & %.2f\\\\\n' % (
            t[0], t[1], t[2], t[3], t[4], ('%.1f' % (100 * t[5])) if t[5] is not None else '---', t[6], t[7]))
